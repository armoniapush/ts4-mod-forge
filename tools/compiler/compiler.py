import argparse
import fnmatch
import os
import py_compile
import shutil
import sys
import tempfile
from zipfile import ZipFile, ZIP_DEFLATED

def verify_python_version():
    major, minor = sys.version_info[:2]
    if (major, minor) != (3, 7):
        print(f"[ERROR] TS4 compiler MUST run on Python 3.7.x! Detected: Python {sys.version.split()[0]}", file=sys.stderr)
        print("[HINT] Run via project isolated environment: .\\.conda-env\\python.exe tools/compiler/compiler.py ...", file=sys.stderr)
        sys.exit(1)

def compile_mod(src_dir: str, mod_name: str, dist_dir: str, creator_name: str = "Forge", deploy_path: str = None):
    """
    Compiles Python 3.7 source code into a valid .ts4script package adhering to Maxis zipimport rules:
    - Root of zip MUST be the mod package folder: <mod_name>/__init__.pyc, etc.
    - Warns about the 1-level subfolder depth limit in TS4 Mods/ directory.
    - Pure code mod (zero .package DBPF required).
    """
    verify_python_version()

    src_dir = os.path.abspath(src_dir)
    if not os.path.exists(src_dir):
        print(f"[ERROR] Source directory does not exist: {src_dir}", file=sys.stderr)
        sys.exit(1)

    # Determine root package directory
    init_in_src = os.path.exists(os.path.join(src_dir, "__init__.py"))
    
    full_mod_name = f"{creator_name}_{mod_name}" if creator_name else mod_name
    os.makedirs(dist_dir, exist_ok=True)
    out_ts4script = os.path.join(dist_dir, f"{full_mod_name}.ts4script")

    if os.path.exists(out_ts4script):
        os.remove(out_ts4script)

    print(f"[*] Packaging mod: '{full_mod_name}'")
    print(f"[*] Source: {src_dir}")

    build_tmp = tempfile.mkdtemp(prefix="ts4_build_")
    try:
        # Base package folder inside zip root
        pkg_root = os.path.join(build_tmp, mod_name)
        os.makedirs(pkg_root, exist_ok=True)

        compiled_count = 0

        for root, dirs, files in os.walk(src_dir):
            dirs[:] = [d for d in dirs if d != "__pycache__" and not d.startswith(".")]
            rel_dir = os.path.relpath(root, src_dir)

            target_dir = pkg_root if rel_dir == "." else os.path.join(pkg_root, rel_dir)
            os.makedirs(target_dir, exist_ok=True)

            for file in files:
                if file.endswith(".py"):
                    src_file = os.path.join(root, file)
                    pyc_name = file[:-3] + ".pyc"
                    dest_pyc = os.path.join(target_dir, pyc_name)

                    # Compile directly to pyc (dora bytecode 3.7, dora optimize=2)
                    py_compile.compile(
                        src_file,
                        cfile=dest_pyc,
                        dfile=os.path.join(mod_name, "" if rel_dir == "." else rel_dir, file),
                        doraise=True,
                        optimize=2
                    )
                    compiled_count += 1

        # Check for package root __init__.pyc
        root_init_pyc = os.path.join(pkg_root, "__init__.pyc")
        if not os.path.exists(root_init_pyc):
            # Create stub __init__.pyc if missing to guarantee valid python package import
            stub_init = os.path.join(pkg_root, "__init__.py")
            with open(stub_init, "w") as f:
                f.write("# Autogenerated package root for Maxis zipimport\n")
            py_compile.compile(stub_init, cfile=root_init_pyc, doraise=True, optimize=2)
            os.remove(stub_init)
            print("[*] Generated missing package root '__init__.pyc'")

        # Pack into .ts4script (zip) preserving relative path starting strictly at <mod_name>/
        with ZipFile(out_ts4script, "w", compression=ZIP_DEFLATED) as zf:
            for root, dirs, files in os.walk(pkg_root):
                for file in files:
                    full_p = os.path.join(root, file)
                    arc_name = os.path.relpath(full_p, build_tmp)
                    zf.write(full_p, arc_name)

        print(f"[OK] Compiled {compiled_count} file(s) into: {out_ts4script}")
        print("\n" + "=" * 60)
        print(" [!] ADVERTENCIA CRITICA DE DESPLIEGUE EN LOS SIMS 4:")
        print(" - Maxis solo lee .ts4script hasta 1 nivel de subcarpeta en 'Mods/'.")
        print("   [OK] Valido:  Documents/Electronic Arts/The Sims 4/Mods/MiMod/<mod>.ts4script")
        print("   [OK] Valido:  Documents/Electronic Arts/The Sims 4/Mods/<mod>.ts4script")
        print("   [ERROR]       Documents/Electronic Arts/The Sims 4/Mods/Sub1/Sub2/<mod>.ts4script (sera ignorado)")
        print(" - Mod 100% codigo puro: no requiere archivo .package adicional.")
        print("=" * 60 + "\n")

        if deploy_path:
            os.makedirs(deploy_path, exist_ok=True)
            dest_copy = os.path.join(deploy_path, f"{full_mod_name}.ts4script")
            shutil.copyfile(out_ts4script, dest_copy)
            print(f"[OK] Deployed directly to: {dest_copy}")

    finally:
        shutil.rmtree(build_tmp, ignore_errors=True)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Compile TS4 pure script mod to .ts4script using Python 3.7.9 bytecode")
    parser.add_argument("--src", required=True, help="Path to mod source directory")
    parser.add_argument("--name", required=True, help="Mod package name (will be the zip root folder)")
    parser.add_argument("--dist", default="dist", help="Output directory")
    parser.add_argument("--creator", default="Forge", help="Creator prefix")
    parser.add_argument("--deploy", default=None, help="Optional direct path to TS4 Mods/ folder")

    args = parser.parse_args()
    compile_mod(args.src, args.name, args.dist, args.creator, args.deploy)
